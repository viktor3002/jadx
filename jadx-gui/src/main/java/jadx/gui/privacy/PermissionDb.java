package jadx.gui.privacy;

import java.io.IOException;
import java.io.InputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.Collections;
import java.util.HashMap;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Properties;

import org.jetbrains.annotations.Nullable;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

import jadx.commons.app.JadxCommonFiles;
import jadx.core.utils.exceptions.JadxRuntimeException;

/**
 * Android API → permission database (SQLite), generated by the {@code jadx-permission-db} module.
 * <br>
 * The bundled database ({@link #RESOURCE}) can be replaced by a newer one without rebuilding
 * jadx: put it at {@code <jadx config dir>/privacy/android-permissions.db}.
 * The whole content is loaded into memory (about 1500 APIs).
 */
public final class PermissionDb {
	private static final Logger LOG = LoggerFactory.getLogger(PermissionDb.class);

	public static final String RESOURCE = "/privacy/android-permissions.db";
	public static final String FILE_NAME = "android-permissions.db";
	public static final int SCHEMA_VERSION = 1;

	public static final String SOURCE_RULES = "rules";

	/**
	 * Permission needed by an API
	 */
	public static final class Requirement {
		private final String permission;
		/** one of the permissions with the same source and mode is enough */
		private final boolean any;
		private final boolean conditional;
		private final @Nullable String access;
		private final @Nullable Integer minApi;
		private final @Nullable Integer maxApi;
		private final String source;

		public Requirement(String permission, boolean any, boolean conditional, @Nullable String access,
				@Nullable Integer minApi, @Nullable Integer maxApi, String source) {
			this.permission = permission;
			this.any = any;
			this.conditional = conditional;
			this.access = access;
			this.minApi = minApi;
			this.maxApi = maxApi;
			this.source = source;
		}

		public String getPermission() {
			return permission;
		}

		public boolean isAny() {
			return any;
		}

		public boolean isConditional() {
			return conditional;
		}

		/**
		 * 'read' or 'write' for content provider access, null otherwise
		 */
		public @Nullable String getAccess() {
			return access;
		}

		public @Nullable Integer getMinApi() {
			return minApi;
		}

		public @Nullable Integer getMaxApi() {
			return maxApi;
		}

		/**
		 * 'sdk-annotations', 'axplorer', 'provider-uri', 'curated' or {@link #SOURCE_RULES}
		 */
		public String getSource() {
			return source;
		}

		@Override
		public String toString() {
			return permission + (any ? " (any)" : "") + " [" + source + ']';
		}
	}

	public enum ApiKind {
		METHOD, FIELD
	}

	public static final class DbApi {
		private final ApiKind kind;
		private final String cls;
		private final String member;
		/** erased parameter types separated by ',', null for fields */
		private final @Nullable String params;
		private final @Nullable String constant;
		private final List<Requirement> requirements = new ArrayList<>();

		DbApi(ApiKind kind, String cls, String member, @Nullable String params, @Nullable String constant) {
			this.kind = kind;
			this.cls = cls;
			this.member = member;
			this.params = params;
			this.constant = constant;
		}

		public ApiKind getKind() {
			return kind;
		}

		public String getCls() {
			return cls;
		}

		public String getMember() {
			return member;
		}

		public @Nullable String getParams() {
			return params;
		}

		/**
		 * Value of a String constant field (inlined in app code)
		 */
		public @Nullable String getConstant() {
			return constant;
		}

		public List<Requirement> getRequirements() {
			return requirements;
		}
	}

	public static final class PermissionInfo {
		private final String name;
		private final @Nullable String protectionLevel;
		private final @Nullable String group;

		PermissionInfo(String name, @Nullable String protectionLevel, @Nullable String group) {
			this.name = name;
			this.protectionLevel = protectionLevel;
			this.group = group;
		}

		public String getName() {
			return name;
		}

		/**
		 * Like 'dangerous', 'normal', 'signature|privileged'
		 */
		public @Nullable String getProtectionLevel() {
			return protectionLevel;
		}

		public @Nullable String getGroup() {
			return group;
		}
	}

	private final Map<String, String> meta;
	private final List<DbApi> apis;
	private final Map<String, PermissionInfo> permissions;
	/** authority -> whole provider requirements (path specific permissions are not used) */
	private final Map<String, List<Requirement>> providers;
	/** broadcast action -> permission needed to receive it */
	private final Map<String, String> broadcastPermissions;

	private PermissionDb(Map<String, String> meta, List<DbApi> apis, Map<String, PermissionInfo> permissions,
			Map<String, List<Requirement>> providers, Map<String, String> broadcastPermissions) {
		this.meta = meta;
		this.apis = apis;
		this.permissions = permissions;
		this.providers = providers;
		this.broadcastPermissions = broadcastPermissions;
	}

	private static volatile @Nullable PermissionDb defaultDb;
	private static volatile boolean defaultLoaded;

	/**
	 * @return database from the jadx config dir if present, else the bundled one; null if loading
	 *         failed (the privacy features then use only the rule table)
	 */
	public static @Nullable PermissionDb getDefault() {
		if (!defaultLoaded) {
			synchronized (PermissionDb.class) {
				if (!defaultLoaded) {
					defaultDb = loadDefault();
					defaultLoaded = true;
				}
			}
		}
		return defaultDb;
	}

	public static Path getOverridePath() {
		return JadxCommonFiles.getConfigDir().resolve("privacy").resolve(FILE_NAME);
	}

	private static @Nullable PermissionDb loadDefault() {
		Path override = getOverridePath();
		if (Files.isRegularFile(override)) {
			try {
				PermissionDb db = load(override);
				LOG.info("Using Android permission database from {} (generated {})", override, db.getMeta("generated"));
				return db;
			} catch (Exception e) {
				LOG.warn("Failed to load Android permission database {}, using bundled one", override, e);
			}
		}
		try {
			return loadBundled();
		} catch (Exception e) {
			LOG.warn("Failed to load bundled Android permission database", e);
			return null;
		}
	}

	public static PermissionDb loadBundled() throws IOException {
		Path tmp = Files.createTempFile("jadx-permissions-", ".db");
		try {
			try (InputStream in = PermissionDb.class.getResourceAsStream(RESOURCE)) {
				if (in == null) {
					throw new IOException("Resource not found: " + RESOURCE);
				}
				Files.copy(in, tmp, StandardCopyOption.REPLACE_EXISTING);
			}
			return load(tmp);
		} finally {
			Files.deleteIfExists(tmp);
		}
	}

	public static PermissionDb load(Path dbFile) throws IOException {
		Properties props = new Properties();
		props.setProperty("open_mode", "1"); // read only
		try (Connection conn = DriverManager.getConnection("jdbc:sqlite:" + dbFile.toAbsolutePath(), props);
				Statement st = conn.createStatement()) {
			Map<String, String> meta = new HashMap<>();
			try (ResultSet rs = st.executeQuery("SELECT key, value FROM meta")) {
				while (rs.next()) {
					meta.put(rs.getString(1), rs.getString(2));
				}
			}
			String schema = meta.get("schema_version");
			if (!Integer.toString(SCHEMA_VERSION).equals(schema)) {
				throw new JadxRuntimeException("Unsupported permission database schema version: " + schema);
			}
			Map<String, PermissionInfo> permissions = new HashMap<>();
			try (ResultSet rs = st.executeQuery("SELECT name, protection_level, permission_group FROM permission")) {
				while (rs.next()) {
					permissions.put(rs.getString(1), new PermissionInfo(rs.getString(1), rs.getString(2), rs.getString(3)));
				}
			}
			Map<Integer, DbApi> apiById = new LinkedHashMap<>();
			try (ResultSet rs = st.executeQuery("SELECT id, kind, class, member, params, constant FROM api ORDER BY id")) {
				while (rs.next()) {
					ApiKind kind = rs.getString(2).equals("field") ? ApiKind.FIELD : ApiKind.METHOD;
					apiById.put(rs.getInt(1), new DbApi(kind, rs.getString(3), rs.getString(4), rs.getString(5), rs.getString(6)));
				}
			}
			try (ResultSet rs = st.executeQuery("SELECT api_id, permission, mode, conditional, access, min_api, max_api, source"
					+ " FROM api_permission ORDER BY api_id, source, permission")) {
				while (rs.next()) {
					DbApi api = apiById.get(rs.getInt(1));
					if (api != null) {
						api.requirements.add(new Requirement(rs.getString(2), "any".equals(rs.getString(3)), rs.getInt(4) != 0,
								rs.getString(5), getInt(rs, 6), getInt(rs, 7), rs.getString(8)));
					}
				}
			}
			Map<String, List<Requirement>> providers = new HashMap<>();
			try (ResultSet rs = st.executeQuery("SELECT authority, access, permission, source FROM provider_permission"
					+ " WHERE path = '' ORDER BY authority, access, permission")) {
				while (rs.next()) {
					providers.computeIfAbsent(rs.getString(1), a -> new ArrayList<>())
							.add(new Requirement(rs.getString(3), true, false, rs.getString(2), null, null, rs.getString(4)));
				}
			}
			Map<String, String> broadcasts = new HashMap<>();
			try (ResultSet rs = st.executeQuery("SELECT action, permission FROM broadcast WHERE permission IS NOT NULL")) {
				while (rs.next()) {
					broadcasts.put(rs.getString(1), rs.getString(2));
				}
			}
			return new PermissionDb(meta, new ArrayList<>(apiById.values()), permissions, providers, broadcasts);
		} catch (SQLException e) {
			throw new IOException("Failed to read permission database: " + dbFile, e);
		}
	}

	private static @Nullable Integer getInt(ResultSet rs, int col) throws SQLException {
		int value = rs.getInt(col);
		return rs.wasNull() ? null : value;
	}

	public @Nullable String getMeta(String key) {
		return meta.get(key);
	}

	/**
	 * Hash of the database content, changes with every content update
	 */
	public String getContentHash() {
		String hash = meta.get("content_hash");
		return hash == null ? "unknown" : hash;
	}

	public List<DbApi> getApis() {
		return apis;
	}

	public @Nullable PermissionInfo getPermission(String name) {
		return permissions.get(name);
	}

	public Map<String, List<Requirement>> getProviders() {
		return Collections.unmodifiableMap(providers);
	}

	public Map<String, String> getBroadcastPermissions() {
		return Collections.unmodifiableMap(broadcastPermissions);
	}
}
